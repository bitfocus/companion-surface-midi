import { RgbColor } from '@companion-surface/base'

export function createControlId(row: number, column: number): string {
	return `${row}/${column}`
}

export function parseControlId(controlId: string): { row: number; column: number } {
	const [rowStr, columnStr] = controlId.split('/')
	return {
		row: parseInt(rowStr, 10),
		column: parseInt(columnStr, 10),
	}
}

function getClosestColor(colors: Uint32Array, rgb: RgbColor): number {
	const { r, g, b } = rgb
	let minDistance = Infinity
	let closestIndex = 0

	for (let i = 0; i < colors.length; i++) {
		const color = colors[i]
		if (color === -1) continue
		const dr = r - ((color >> 16) & 0xff)
		const dg = g - ((color >> 8) & 0xff)
		const db = b - (color & 0xff)
		const colorDiff = dr * dr + dg * dg + db * db

		if (colorDiff < minDistance) {
			minDistance = colorDiff
			closestIndex = i
		}
	}
	return closestIndex
}

